import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

/** 使用隔离本机服务和正式页面。磁盘操作模拟作者放入旧稿及用其他编辑器修改。 */
export default async function verifyChapterWorkspace(page) {
  const origin = new URL(page.url()).origin;
  const root = await mkdtemp(join(tmpdir(), 'plotloom-chapters-ui-'));
  const create = await page.request.post(origin + '/api/workspaces', { data: { title: '海潮', root } });
  assert.equal(create.status(), 201);
  const book = await create.json();
  const url = origin + '/#workspace=' + book.id;
  const button = name => page.getByRole('button', { name, exact: true });
  const chapters = page.getByRole('region', { name: '正文章节工作区' });
  const editor = chapters.getByRole('textbox', { name: '文稿正文' });
  const replaceText = async value => {
    await editor.focus();
    await page.keyboard.press('Control+a');
    await page.keyboard.insertText(value);
  };
  const pick = name => chapters.getByRole('button', { name, exact: true }).click();
  await page.goto(url);
  await page.getByRole('heading', { name: '继续创作《海潮》' }).waitFor();
  const chat = page.getByRole('textbox', { name: '输入消息，/ 调用技能，@ 引用文件' });
  await chat.fill('等我核对第三章。');
  await button('打开工作区').click();
  await chapters.getByText(/此目录还没有 Markdown 文稿/).waitFor();
  const path = join(root, '正文章节', '第三章.md');
  const initial = '# 潮声\r\n\r\n**靠岸**。\r\n';
  const saved = initial.replace('靠岸', '收帆');
  await writeFile(path, initial);
  await writeFile(join(root, '正文章节', '第一章.md'), '# 开篇\n\n' + '潮水拍着石阶。\n\n'.repeat(120));
  await writeFile(join(root, '大纲', '不属于章节.md'), '大纲');
  await chapters.locator('.plotloom-paper-toolbar').getByRole('button', { name: '刷新文稿' }).click();
  await chapters.getByRole('button', { name: '第三章.md' }).waitFor();
  assert.deepEqual(await chapters.locator('.pl-document-list-item').evaluateAll(items => items.map(item => item.getAttribute('aria-label'))), ['第一章.md', '第三章.md']);
  const outlineTab = chapters.getByRole('tab', { name: '大纲' });
  const textTab = chapters.getByRole('tab', { name: '正文' });
  await outlineTab.click();
  await pick('不属于章节.md');
  await chapters.getByText('已保存', { exact: true }).waitFor();
  assert.equal(await editor.innerText(), '大纲');
  await outlineTab.focus();
  await page.keyboard.press('ArrowLeft');
  assert.equal(await textTab.getAttribute('aria-selected'), 'true');
  await pick('第三章.md');
  await chapters.getByText('已保存', { exact: true }).waitFor();
  await replaceText('可撤销的试写');
  assert.equal(await editor.innerText(), '可撤销的试写');
  await page.keyboard.press('Control+z');
  assert.match(await editor.innerText(), /靠岸/);
  await replaceText(saved.replaceAll('\r\n', '\n'));
  await chapters.getByRole('tab', { name: '预览', exact: true }).click();
  await chapters.getByRole('heading', { name: '潮声' }).waitFor();
  const rendered = await chapters.getByRole('article', { name: '章节预览' }).innerText();
  assert.match(rendered, /收帆。/);
  assert.doesNotMatch(rendered, /\*\*|# 潮声/);
  assert.equal(await chapters.getByRole('button', { name: '保存', exact: true }).count(), 0);
  await button('收起工作区').click();
  assert.equal(await chat.inputValue(), '等我核对第三章。');
  await button('打开工作区').click();
  await page.reload();
  await chapters.getByRole('heading', { name: '潮声' }).waitFor();
  await chapters.getByText('已保存', { exact: true }).waitFor();
  assert.equal(await readFile(path, 'utf8'), saved);
  await button('定稿').click();
  await page.getByText('已留档定稿', { exact: true }).waitFor();
  await chapters.getByRole('tab', { name: '编辑', exact: true }).click();
  await replaceText('保留这份草稿');
  await writeFile(path, '另一位编辑改的正文');
  await pick('第一章.md');
  await chapters.getByText('已保存', { exact: true }).waitFor();
  await chapters.getByRole('tab', { name: '预览', exact: true }).click();
  const reading = chapters.getByRole('article', { name: '章节预览' });
  await reading.getByRole('heading', { name: '开篇' }).waitFor();
  await reading.evaluate(node => { node.scrollTop = 320; });
  await page.waitForFunction(() => Object.keys(sessionStorage).some(key => key.endsWith(':preview') && Number(sessionStorage.getItem(key)) > 0));
  await chapters.getByRole('tab', { name: '编辑', exact: true }).click();
  await chapters.getByRole('tab', { name: '预览', exact: true }).click();
  assert((await reading.evaluate(node => node.scrollTop)) > 0);
  await pick('第三章.md');
  await chapters.getByText('磁盘文稿已有新版本。当前仍显示草稿。').waitFor();
  assert.equal(await editor.innerText(), '保留这份草稿');
  assert.equal(await readFile(path, 'utf8'), '另一位编辑改的正文');
  await button('定稿选项').click();
  await page.getByRole('menuitem', { name: '定稿记录' }).click();
  const conflictHistory = page.getByRole('dialog', { name: '定稿记录' });
  await conflictHistory.getByLabel('定稿预览').getByText(/收帆/).waitFor();
  assert(await conflictHistory.getByRole('button', { name: '恢复所选定稿' }).isDisabled());
  await conflictHistory.getByRole('button', { name: '关闭', exact: true }).last().click();
  await button('丢弃草稿').click();
  await page.setViewportSize({ width: 440, height: 840 });
  await button('定稿选项').click();
  await page.getByRole('menuitem', { name: '定稿记录' }).click();
  const history = page.getByRole('dialog', { name: '定稿记录' });
  await history.getByRole('combobox').click();
  await page.getByRole('option').first().waitFor();
  assert.equal(await page.getByRole('option').count(), 1);
  await page.getByRole('option').first().click();
  await history.getByLabel('定稿预览').getByText(/收帆/).waitFor();
  await button('恢复所选定稿').click();
  await history.waitFor({ state: 'hidden' });
  assert.equal(await readFile(path, 'utf8'), saved);
  await page.setViewportSize({ width: 440, height: 840 });
  const ball = chapters.getByRole('button', { name: '文稿目录', exact: true });
  const directory = chapters.getByRole('navigation', { name: '文稿目录' });
  await ball.waitFor();
  await directory.waitFor({ state: 'hidden' });
  const paper = chapters.locator('.plotloom-chapter-paper');
  const width = (await paper.boundingBox()).width;
  await ball.hover();
  await directory.waitFor();
  await textTab.hover();
  assert.equal((await paper.boundingBox()).width, width);
  await pick('第三章.md');
  await directory.waitFor({ state: 'hidden' });
  await ball.press('Enter');
  await directory.waitFor();
  await directory.getByRole('button', { name: '第一章.md', exact: true }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '删除章节' }).click();
  await page.getByRole('dialog', { name: '删除章节' }).getByRole('button', { name: '取消' }).click();
  assert.match(await readFile(join(root, '正文章节', '第一章.md'), 'utf8'), /开篇/);
  await ball.press('Enter');
  await directory.waitFor();
  await ball.press('Escape');
  await directory.waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 720, height: 840 });
  await chapters.getByRole('tab', { name: '预览', exact: true }).click();
  await chapters.getByRole('heading', { name: '潮声' }).waitFor();
  await button('收起工作区').click();
  await chat.waitFor();
  // 同一章节也能在已经创建的小说会话旁打开，项目对话没有本书的章节入口。
  const session = await (await page.request.post(origin + '/api/workspaces/' + book.id + '/sessions', { data: { name: '海潮创作' } })).json();
  await page.goto(origin + '/#chat=' + session.id);
  await page.getByRole('region', { name: '聊天', exact: true }).waitFor();
  await button('打开工作区').click();
  await chapters.getByRole('heading', { name: '潮声' }).waitFor();
  await button('收起工作区').click();
  const agentPreview = 'WRITE:' + JSON.stringify({ steps: [{ name: 'manuscript_workspace',
    args: { action: 'preview', path: '大纲/不属于章节.md' } }] });
  for (const approve of [false, true]) {
    await page.goto(url);
    await page.getByRole('heading', { name: '继续创作《海潮》' }).waitFor();
    // 等编辑器恢复本书草稿后，再使用真实键盘输入更新应用维护的草稿。
    await chat.click();
    await page.keyboard.press('Control+a');
    await page.keyboard.insertText(agentPreview);
    assert.equal(await chat.inputValue(), agentPreview);
    await button('发送').click();
    const question = page.getByRole('form', { name: /预览文稿/ });
    await question.getByRole('radio', { name: approve ? /确认操作/ : /取消操作/ }).check();
    await question.getByRole('button', { name: '发送' }).click();
    await question.waitFor({ state: 'hidden' });
    if (approve) {
      const id = new URLSearchParams(new URL(page.url()).hash.slice(1)).get('chat');
      await page.waitForFunction(async id => {
        const response = await fetch('/api/sessions/' + id);
        return (await response.json()).manuscriptRequest?.view.mode === 'preview';
      }, id);
      await chapters.getByRole('article', { name: '章节预览' }).getByText('大纲', { exact: true }).waitFor();
    }
    else await button('打开工作区').waitFor();
    await page.waitForFunction(() => !document.querySelector('[aria-label="停止任务"]'));
  }
  await page.goto(origin + '/');
  await button('打开工作区').click();
  assert.equal(await page.getByRole('tab', { name: '正文章节' }).count(), 0);
  return '章节目录、聊天草稿、即时预览、刷新恢复、版本冲突与历史、窄屏和会话归属通过';
}
