// Playwright CLI：在产品页面 run-code --filename tests/ui/workspace-frame-browser.js
async (page) => {
  const passed = [], errors = [];
  const assert = (ok, name) => { if (!ok) throw new Error(name); passed.push(name); };
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.goto(new URL('/', page.url()).href);
  const workspace = page.getByRole('dialog', { name: '内容工作区' });
  await page.getByRole('button', { name: '打开工作区', exact: true }).click();
  await workspace.waitFor();
  const search = workspace.getByRole('searchbox', { name: '搜索工作区功能' });
  await search.fill('文档');
  assert(await workspace.getByRole('button', { name: 'Markdown 预览', exact: true }).isVisible(), '功能关键词可过滤卡片');
  assert(await workspace.getByRole('button', { name: '浏览器', exact: true }).count() === 0, '隐藏未匹配卡片');
  await search.fill('无匹配入口');
  assert(await workspace.getByText('未找到匹配的功能').isVisible(), '搜索无结果提示');
  await search.fill('');
  await page.screenshot({ path: 'output/playwright/workspace-start.png' });
  await workspace.getByRole('button', { name: '浏览器', exact: true }).click();
  const address = workspace.getByRole('textbox', { name: '网页地址' });
  await address.fill('https://example.org/my-draft');
  const original = await address.elementHandle();
  assert(await workspace.getByRole('heading', { name: '浏览器尚未连接' }).isVisible(), '诚实展示未连接状态');
  assert(await workspace.getByRole('button', { name: '后退', exact: true }).isDisabled(), '不可用浏览器动作禁用');
  await workspace.getByRole('button', { name: '新建标签', exact: true }).click();
  await workspace.getByRole('button', { name: 'Markdown 预览', exact: true }).click();
  assert(await workspace.getByRole('heading', { name: '尚未打开文档' }).isVisible(), '文档拥有独立内容');
  assert(await address.count() === 0, '隐藏浏览器内容退出可访问树');
  await workspace.getByRole('button', { name: '新建标签', exact: true }).click();
  await workspace.getByRole('button', { name: '图片预览', exact: true }).click();
  assert(await workspace.getByRole('heading', { name: '尚未打开图片' }).isVisible(), '图片拥有独立内容');
  const contentBox = await workspace.locator('.pl-workspace-tabs__page:visible').boundingBox();
  for (let i = 0; i < 4; i++) {
    await workspace.getByRole('tab', { name: '浏览器', exact: true }).click();
    await workspace.getByRole('tab', { name: 'Markdown 预览', exact: true }).click();
  }
  const otherBox = await workspace.locator('.pl-workspace-tabs__page:visible').boundingBox();
  assert(contentBox.y === otherBox.y && contentBox.height === otherBox.height, '快速切换保持完整页面框架锚点与高度');
  assert(await workspace.locator('.pl-workspace-tabs__page:visible > .pl-workspace-tabs__toolbar').count() === 0, '独立阅读器不叠加默认工具栏');
  await workspace.getByRole('tab', { name: '浏览器', exact: true }).click();
  assert(await address.inputValue() === 'https://example.org/my-draft' && await original.evaluate(el => el.isConnected), '切换保留同一个页面节点与地址草稿');
  await page.keyboard.press('ArrowRight');
  assert(await workspace.getByRole('tab', { name: 'Markdown 预览', exact: true }).getAttribute('aria-selected') === 'true', '方向键切换标签');
  await page.keyboard.press('End');
  assert(await workspace.getByRole('tab', { name: '图片预览', exact: true }).getAttribute('aria-selected') === 'true', 'End选中末尾标签');
  await workspace.getByRole('button', { name: '关闭标签：Markdown 预览', exact: true }).click();
  assert(await workspace.getByRole('tab', { name: '图片预览', exact: true }).getAttribute('aria-selected') === 'true', '关闭后台标签不改变当前页');
  await workspace.getByRole('button', { name: '关闭标签：图片预览', exact: true }).click();
  assert(await workspace.getByRole('tab', { name: '浏览器', exact: true }).getAttribute('aria-selected') === 'true', '关闭当前页选择相邻页');
  await workspace.getByRole('button', { name: '收起工作区' }).click();
  await workspace.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '打开工作区' }).click();
  assert(await address.inputValue() === 'https://example.org/my-draft', '收起重开保留页面状态');
  const separator = page.getByRole('separator', { name: '调整右侧面板宽度' });
  const before = await workspace.boundingBox();
  await separator.focus(); await page.keyboard.press('ArrowLeft');
  assert((await workspace.boundingBox()).width > before.width, '分栏可以键盘调宽');
  await page.screenshot({ path: 'output/playwright/workspace-frame-desktop.png' });
  await page.setViewportSize({ width: 760, height: 860 });
  await page.waitForTimeout(200);
  assert(await workspace.evaluate(el => el.matches(':modal')), '窄屏使用模态工作区');
  assert(await address.inputValue() === 'https://example.org/my-draft', '宽窄切换保留标签状态');
  await page.keyboard.press('Escape');
  await workspace.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '打开工作区' }).click();
  await page.screenshot({ path: 'output/playwright/workspace-frame-narrow.png' });
  await workspace.getByRole('button', { name: '关闭标签：浏览器' }).click();
  assert(await workspace.getByRole('heading', { name: '没有打开的标签' }).isVisible(), '最后标签关闭展示空态');
  await workspace.getByRole('button', { name: '新建标签', exact: true }).first().click();
  assert(await workspace.getByRole('tab', { name: '新标签页' }).isVisible(), '空工作区可以重新新增');
  assert(!errors.length, `运行时无错误：${errors.join('; ')}`);
  return { passed, total: passed.length };
}
