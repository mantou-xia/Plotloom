// Playwright CLI：run-code --filename tests/ui/source-reference-browser.js
async (page) => {
  const passed = [], errors = [];
  const assert = (ok, name) => { if (!ok) throw new Error(name); passed.push(name); };
  const onError = error => errors.push(error.message);
  page.on('pageerror', onError);
  const frame = page.frameLocator('iframe');
  const root = frame.getByRole('region', { name: '引用来源', exact: true });
  const items = root.locator('.pl-source-reference__item');
  const dialog = frame.getByRole('dialog', { name: '来源详情', exact: true });
  const select = async value => { await page.locator('#example-state').selectOption(value); await page.waitForTimeout(160); };
  const same = (a, b) => ['x', 'y', 'width', 'height'].every(k => Math.abs(a[k] - b[k]) < .1);
  try {
    await page.setViewportSize({ width: 1700, height: 1100 });
    await page.getByRole('button', { name: 'SourceReference 7', exact: true }).click();
    await select('mixed');
    await items.first().waitFor();
    assert(await items.count() === 2, '网页和文件共用来源列表');
    assert(await items.first().locator('.pl-source-reference__location').textContent() === 'example.com', '域名来自实际 URL');
    assert(await items.nth(1).locator('.pl-source-reference__location').textContent() === '资料/人物关系记录.md', '文件展示传入路径');
    await root.screenshot({ path: 'output/playwright/source-reference-list.png' });
    const listBefore = await root.boundingBox();
    await items.first().focus(); await page.keyboard.press('Enter'); await dialog.waitFor();
    assert(await dialog.locator('dd').textContent() === 'https://example.com/research/story-structure', '详情展示完整网页链接');
    assert(await dialog.locator('blockquote').textContent() === await page.getByRole('textbox', { name: '引用片段', exact: true }).inputValue(), '引用片段保留原文和换行');
    const link = dialog.getByRole('link', { name: '打开网页' });
    assert(await link.getAttribute('target') === '_blank' && (await link.getAttribute('rel')).includes('noopener'), '网页在隔离的新窗口打开');
    const route = async route => route.fulfill({ status: 200, contentType: 'text/html', body: '<title>来源导航测试</title>' });
    await page.context().route('https://example.com/**', route);
    try {
      const [popup] = await Promise.all([page.waitForEvent('popup'), link.click()]);
      await popup.waitForLoadState();
      assert(popup.url() === 'https://example.com/research/story-structure', '实际点击导航到对应链接（拦截网络验证）');
      await popup.close();
    } finally { await page.context().unroute('https://example.com/**', route); }
    await dialog.screenshot({ path: 'output/playwright/source-reference-web.png' });
    await page.keyboard.press('Escape');
    assert(await items.first().evaluate(el => el.ownerDocument.activeElement === el), '关闭详情后恢复列表按钮焦点');
    assert(same(listBefore, await root.boundingBox()), '打开和关闭详情不改变来源列表位置尺寸');
    await items.nth(1).click(); await dialog.waitFor();
    assert(await dialog.locator('dd').textContent() === '资料/人物关系记录.md', '文件详情保留完整路径');
    assert(await dialog.locator('a[href^="file:"]').count() === 0, '文件路径不会转换成本机链接');
    const before = await dialog.boundingBox();
    await dialog.getByRole('button', { name: '打开文件', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'onOpenFile(file-2)' }).waitFor();
    assert(same(before, await dialog.boundingBox()), '文件回调反馈不改变详情布局');
    await page.keyboard.press('Escape');
    await page.getByRole('checkbox', { name: '提供文件打开操作', exact: true }).uncheck();
    await items.nth(1).click(); await dialog.waitFor();
    assert(await dialog.getByRole('button', { name: '打开文件' }).count() === 0 && await dialog.getByText('暂无法打开此文件').isVisible(), '没有文件回调时不提供无效打开按钮');
    await page.keyboard.press('Escape');
    await select('citations');
    const markers = frame.locator('.pl-citation-marker');
    await markers.nth(1).focus(); await page.keyboard.press('Space'); await dialog.waitFor();
    assert(await dialog.getByRole('article', { name: '来源 2', exact: true }).isVisible(), 'C10 文件编号打开同 ID 的来源详情');
    await page.keyboard.press('Escape');
    assert(await markers.nth(1).evaluate(el => el.ownerDocument.activeElement === el), 'C10 打开详情后焦点回到原编号');
    await markers.first().click(); await dialog.waitFor();
    assert(await dialog.getByRole('article', { name: '来源 1', exact: true }).isVisible(), 'C10 网页编号打开对应网页来源');
    await page.keyboard.press('Escape');
    await select('invalid-link'); await items.click(); await dialog.waitFor();
    assert(await dialog.getByRole('link').count() === 0 && await dialog.getByText('链接不可用').isVisible(), '脚本 URL 不提供导航');
    assert(await dialog.locator('dd').textContent() === 'javascript:alert(1)', '无效链接保留原始文本以便检查');
    await page.keyboard.press('Escape');
    await page.getByRole('textbox', { name: '网页链接', exact: true }).fill('这不是网址');
    await items.click(); await dialog.waitFor();
    assert(await dialog.getByRole('link').count() === 0, '无效 URL 不产生可点击链接');
    await page.keyboard.press('Escape');
    await select('long');
    await page.getByRole('button', { name: '窄屏', exact: true }).click();
    assert(await root.evaluate(el => el.scrollWidth <= el.clientWidth + 1), '窄屏长标题与路径不撑破列表');
    await items.click(); await dialog.waitFor();
    assert(await dialog.locator('dd').textContent() === await page.getByRole('textbox', { name: '文件路径', exact: true }).inputValue(), '长路径在详情中完整保留');
    assert(await dialog.locator('blockquote').textContent() === await page.getByRole('textbox', { name: '引用片段', exact: true }).inputValue(), '长引用片段在详情中不截断');
    assert(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1), '窄屏详情不横向溢出');
    const viewport = dialog.locator('.pl-dialog__body');
    assert(await viewport.evaluate(el => el.scrollHeight > el.clientHeight), '长详情进入独立滚动区');
    const closeBefore = await dialog.getByRole('button', { name: '关闭弹窗' }).boundingBox();
    await viewport.evaluate(el => { el.scrollTop = el.scrollHeight; });
    assert(same(closeBefore, await dialog.getByRole('button', { name: '关闭弹窗' }).boundingBox()), '阅读长详情时关闭按钮保持原位');
    await dialog.screenshot({ path: 'output/playwright/source-reference-narrow.png' });
    await page.keyboard.press('Escape');
    await select('file');
    await page.getByRole('textbox', { name: '引用片段', exact: true }).fill('<script>字面内容</script>\n  保留缩进');
    await page.getByRole('textbox', { name: '来源摘要', exact: true }).fill('');
    await items.click(); await dialog.waitFor();
    assert(await dialog.locator('blockquote').textContent() === '<script>字面内容</script>\n  保留缩进' && await dialog.locator('script').count() === 0, '来源内容作为纯文本，不执行 HTML');
    assert(await dialog.getByRole('heading', { name: '摘要', exact: true }).count() === 0, '缺失摘要不补造占位内容');
    await page.keyboard.press('Escape');
    await select('empty');
    assert(await items.count() === 0 && await root.getByText('暂无来源').isVisible(), '空列表不补造来源');
    assert(errors.length === 0, '无浏览器未捕获异常');
    return { passed: passed.length, assertions: passed };
  } finally { page.off('pageerror', onError); }
}
